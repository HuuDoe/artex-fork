// Package stealth centralizes everything that makes tool-originated HTTP look
// like ordinary browser traffic on the wire: a realistic browser User-Agent
// rotation, the headers real browsers send, and a utls-based transport whose
// ClientHello mirrors Chrome instead of Go's distinctive TLS fingerprint
// (JA3/JA4). Direct tool requests (webfetch, enrich probes, custom HTTP tools)
// should all go through NewTransport so a WAF can't fingerprint them as Go.
package stealth

import (
	"context"
	"crypto/tls"
	"math/rand"
	"net"
	"net/http"
	"time"

	utls "github.com/refraction-networking/utls"
)

// browserProfile is one coherent browser identity. UA, Accept-Language and the
// client-hint header must agree — mixing a Chrome UA with Firefox-style headers
